// Crypto polyfill - MUST be first import before anything else
import 'react-native-get-random-values';

import { Buffer } from '@craftzdog/react-native-buffer';

import { DarkTheme, ThemeProvider as NavigationThemeProvider } from '@react-navigation/native';
import { WdkAppProvider } from '@tetherto/wdk-react-native-core';
import { ThemeProvider } from '@tetherto/wdk-uikit-react-native';
import { Stack } from 'expo-router';
import * as SplashScreen from 'expo-splash-screen';
import { StatusBar } from 'expo-status-bar';
import { useEffect, useMemo, useState } from 'react';
import { View } from 'react-native';
import { GestureHandlerRootView } from 'react-native-gesture-handler';
import 'react-native-reanimated';
import { SparkNetworkMode } from '@/config/get-chains-config';
import { getWdkConfigs } from '@/config/get-wdk-configs';
// Worklet bundle generated by `npx wdk-worklet-bundler generate` (see wdk.config.js).
// This is what carries the WDK engine plus the Orchestra swidge protocol.
import bundle from '../../wdk-bundle/wdk-worklet.bundle.js';
import { Toaster } from 'sonner-native';
import { colors } from '@/constants/colors';
import { getNetworkMode } from '@/services/network-mode-service';
import { pricingService } from '@/services/pricing-service';
// @ts-ignore
global.Buffer = Buffer as unknown as BufferConstructor;

SplashScreen.preventAutoHideAsync();

const CustomDarkTheme = {
  ...DarkTheme,
  colors: {
    ...DarkTheme.colors,
    background: colors.background,
    card: colors.background,
  },
};

export default function RootLayout() {
  const [sparkNetwork, setSparkNetwork] = useState<SparkNetworkMode>('MAINNET');
  const [isReady, setIsReady] = useState(false);
  const wdkConfigs = useMemo(() => getWdkConfigs(sparkNetwork), [sparkNetwork]);

  useEffect(() => {
    const init = async () => {
      const mode = await getNetworkMode();
      // Use REGTEST for testnet mode, MAINNET for mainnet
      setSparkNetwork(mode === 'testnet' ? 'REGTEST' : 'MAINNET');
      // Pricing must initialise here at the root: index.tsx also does it, but
      // in dev Expo Router can restore straight to a deep route and never
      // mount index at all. Fire-and-forget — prices are cosmetic and must
      // not hold up the splash screen.
      pricingService
        .initialize()
        .catch((error) => console.error('Failed to initialize pricing service:', error));
      setIsReady(true);
      SplashScreen.hideAsync();
    };
    init();
  }, []);

  if (!isReady) {
    return null;
  }

  return (
    <GestureHandlerRootView style={{ flex: 1 }}>
      <ThemeProvider
        defaultMode="dark"
        brandConfig={{
          primaryColor: colors.primary,
        }}
      >
        <WdkAppProvider bundle={{ bundle }} wdkConfigs={wdkConfigs}>
          <NavigationThemeProvider value={CustomDarkTheme}>
            <View style={{ flex: 1, backgroundColor: colors.background }}>
              <Stack
                screenOptions={{
                  headerShown: false,
                  contentStyle: { backgroundColor: colors.background },
                }}
              />
              <StatusBar style="light" />
            </View>
          </NavigationThemeProvider>
        </WdkAppProvider>
        <Toaster
          offset={90}
          toastOptions={{
            style: {
              backgroundColor: colors.background,
              borderWidth: 1,
              borderColor: colors.border,
            },
            titleStyle: { color: colors.text },
            descriptionStyle: { color: colors.text },
          }}
        />
      </ThemeProvider>
    </GestureHandlerRootView>
  );
}
